# List Methods - Used for only for Lists

# l.append(value) - at one element at end of list
# l.insert(index,value) - Insert element at specific index
# l.sort() - Arranges in increasing order
# l.reverse() - Reverser order

nums = [1,2,3]

nums.append(4)
print(nums)

nums.insert(0,0)
print(nums)

nums.insert(1,10)
print(nums)

nums.sort()
print(nums)

nums.reverse()
print(nums)