# Creaate Calc User Asked.

i1 = int(input("Enter your 1st number: "))
i2 = int(input("Enter your 2nd number: "))

op = input("Enter operator to calc: +, -, /, *")

if op == '+':
    print(i1 + i2)
elif op == '-':
    print(i1 - i2)
elif op == '/':
    print(i1 / i2)
elif op == '*':
    print(i1 * i2)

